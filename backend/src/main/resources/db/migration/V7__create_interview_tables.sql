CREATE TABLE interview_session
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    member_id          BIGINT                                  NOT NULL,
    status             VARCHAR(20)                             NOT NULL,
    started_at         TIMESTAMP WITH TIME ZONE                NOT NULL,
    completed_at       TIMESTAMP WITH TIME ZONE,
    current_turn_order INTEGER                                 NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_interview_session PRIMARY KEY (id),
    CONSTRAINT fk_interview_session_member
        FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE
);

-- 진행 중인 회원 면접을 시작 시각 순으로 조회하는 쿼리를 지원한다.
CREATE INDEX idx_interview_session_member_status_started_at
    ON interview_session (member_id, status, started_at);

CREATE TABLE interview_core_question
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    interview_session_id BIGINT                                  NOT NULL,
    source_question_id   BIGINT,
    content              TEXT                                    NOT NULL,
    category             VARCHAR(50)                             NOT NULL,
    question_order       INTEGER                                 NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_interview_core_question PRIMARY KEY (id),
    CONSTRAINT uk_interview_core_question_session_order
        UNIQUE (interview_session_id, question_order),
    CONSTRAINT uk_interview_core_question_session_category
        UNIQUE (interview_session_id, category),
    CONSTRAINT fk_interview_core_question_session
        FOREIGN KEY (interview_session_id) REFERENCES interview_session (id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_core_question_source
        FOREIGN KEY (source_question_id) REFERENCES question (id) ON DELETE SET NULL
);

-- 원본 질문 삭제 시 참조 중인 스냅샷을 찾는 작업을 지원한다.
CREATE INDEX idx_interview_core_question_source_question_id
    ON interview_core_question (source_question_id);

CREATE TABLE follow_up_question
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    interview_core_question_id BIGINT                                  NOT NULL,
    content                    TEXT                                    NOT NULL,
    created_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_follow_up_question PRIMARY KEY (id),
    CONSTRAINT uk_follow_up_question_core_question UNIQUE (interview_core_question_id),
    CONSTRAINT fk_follow_up_question_core_question
        FOREIGN KEY (interview_core_question_id) REFERENCES interview_core_question (id) ON DELETE CASCADE
);

CREATE TABLE interview_turn
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    interview_session_id       BIGINT                                  NOT NULL,
    turn_order                 INTEGER                                 NOT NULL,
    turn_type                  VARCHAR(20)                             NOT NULL,
    interview_core_question_id BIGINT,
    follow_up_question_id      BIGINT,
    created_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_interview_turn PRIMARY KEY (id),
    CONSTRAINT uk_interview_turn_session_order UNIQUE (interview_session_id, turn_order),
    CONSTRAINT uk_interview_turn_core_question UNIQUE (interview_core_question_id),
    CONSTRAINT uk_interview_turn_follow_up_question UNIQUE (follow_up_question_id),
    CONSTRAINT fk_interview_turn_session
        FOREIGN KEY (interview_session_id) REFERENCES interview_session (id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_turn_core_question
        FOREIGN KEY (interview_core_question_id) REFERENCES interview_core_question (id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_turn_follow_up_question
        FOREIGN KEY (follow_up_question_id) REFERENCES follow_up_question (id) ON DELETE CASCADE,
    CONSTRAINT chk_interview_turn_question_type CHECK
        (
            (
                turn_type = 'CORE'
                AND interview_core_question_id IS NOT NULL
                AND follow_up_question_id IS NULL
            )
            OR
            (
                turn_type = 'FOLLOW_UP'
                AND interview_core_question_id IS NULL
                AND follow_up_question_id IS NOT NULL
            )
        )
);
