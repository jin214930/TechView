CREATE TABLE answer
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    interview_turn_id   BIGINT                                  NOT NULL,
    audio_object_key    VARCHAR(1024)                            NOT NULL,
    audio_content_type  VARCHAR(100)                             NOT NULL,
    audio_duration_ms   INTEGER                                  NOT NULL,
    transcript          TEXT,
    transcribed_at      TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE                 NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE                 NOT NULL,
    CONSTRAINT pk_answer PRIMARY KEY (id),
    CONSTRAINT uk_answer_interview_turn UNIQUE (interview_turn_id),
    CONSTRAINT fk_answer_interview_turn
        FOREIGN KEY (interview_turn_id) REFERENCES interview_turn (id) ON DELETE CASCADE,
    CONSTRAINT chk_answer_audio_duration_positive CHECK (audio_duration_ms > 0)
);
