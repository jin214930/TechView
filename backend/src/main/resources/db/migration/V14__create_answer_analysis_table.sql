CREATE TABLE answer_analysis
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    answer_id            BIGINT                                  NOT NULL,
    summary              TEXT                                    NOT NULL,
    strengths            JSONB                                   NOT NULL,
    improvements         JSONB                                   NOT NULL,
    follow_up_decision   VARCHAR(20)                             NOT NULL,
    follow_up_reason     TEXT                                    NOT NULL,
    model                VARCHAR(100)                            NOT NULL,
    prompt_version       VARCHAR(100)                            NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE                NOT NULL,

    CONSTRAINT pk_answer_analysis
        PRIMARY KEY (id),

    CONSTRAINT uk_answer_analysis_answer_id
        UNIQUE (answer_id),

    CONSTRAINT fk_answer_analysis_answer
        FOREIGN KEY (answer_id)
            REFERENCES answer (id)
            ON DELETE CASCADE,

    CONSTRAINT chk_answer_analysis_follow_up_decision
        CHECK (follow_up_decision IN ('ASK', 'SKIP')),

    CONSTRAINT chk_answer_analysis_strengths
        CHECK (
            CASE
                WHEN jsonb_typeof(strengths) = 'array'
                    THEN jsonb_array_length(strengths) <= 3
                ELSE FALSE
            END
        ),

    CONSTRAINT chk_answer_analysis_improvements
        CHECK (
            CASE
                WHEN jsonb_typeof(improvements) = 'array'
                    THEN jsonb_array_length(improvements) <= 3
                ELSE FALSE
            END
        )
);
