CREATE TABLE interview_feedback
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    interview_session_id BIGINT                                  NOT NULL,
    overall_summary      TEXT                                    NOT NULL,
    strengths            JSONB                                   NOT NULL,
    improvements         JSONB                                   NOT NULL,
    category_feedbacks   JSONB                                   NOT NULL,
    recommended_topics   JSONB                                   NOT NULL,
    model                VARCHAR(100)                            NOT NULL,
    prompt_version       VARCHAR(100)                            NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE                NOT NULL,

    CONSTRAINT pk_interview_feedback
        PRIMARY KEY (id),

    CONSTRAINT uk_interview_feedback_session_id
        UNIQUE (interview_session_id),

    CONSTRAINT fk_interview_feedback_session
        FOREIGN KEY (interview_session_id)
            REFERENCES interview_session (id)
            ON DELETE CASCADE,

    CONSTRAINT chk_interview_feedback_strengths
        CHECK (
            CASE
                WHEN jsonb_typeof(strengths) = 'array'
                    THEN jsonb_array_length(strengths) BETWEEN 1 AND 3
                ELSE FALSE
            END
        ),

    CONSTRAINT chk_interview_feedback_improvements
        CHECK (
            CASE
                WHEN jsonb_typeof(improvements) = 'array'
                    THEN jsonb_array_length(improvements) BETWEEN 1 AND 3
                ELSE FALSE
            END
        ),

    CONSTRAINT chk_interview_feedback_category_feedbacks
        CHECK (
            CASE
                WHEN jsonb_typeof(category_feedbacks) = 'array'
                    THEN jsonb_array_length(category_feedbacks) = 5
                ELSE FALSE
            END
        ),

    CONSTRAINT chk_interview_feedback_recommended_topics
        CHECK (
            CASE
                WHEN jsonb_typeof(recommended_topics) = 'array'
                    THEN jsonb_array_length(recommended_topics) BETWEEN 1 AND 3
                ELSE FALSE
            END
        )
);

-- 한 면접 세션에는 종합 피드백 생성 작업을 하나만 등록할 수 있다.
CREATE UNIQUE INDEX uk_processing_job_final_feedback_session
    ON processing_job (interview_session_id)
    WHERE job_type = 'FINAL_FEEDBACK_GENERATION';
