CREATE TABLE processing_job
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    interview_session_id BIGINT                                  NOT NULL,
    answer_id            BIGINT,
    job_type             VARCHAR(50)                             NOT NULL,
    status               VARCHAR(20)                             NOT NULL,
    attempt_count        INTEGER                                 NOT NULL,
    max_attempts         INTEGER                                 NOT NULL,
    next_attempt_at      TIMESTAMP WITH TIME ZONE,
    lease_expires_at     TIMESTAMP WITH TIME ZONE,
    error_code           VARCHAR(100),
    error_message        TEXT,
    created_at           TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE                NOT NULL,

    CONSTRAINT pk_processing_job
        PRIMARY KEY (id),

    CONSTRAINT fk_processing_job_interview_session
        FOREIGN KEY (interview_session_id)
            REFERENCES interview_session (id)
            ON DELETE CASCADE,

    CONSTRAINT fk_processing_job_answer
        FOREIGN KEY (answer_id)
            REFERENCES answer (id)
            ON DELETE CASCADE,

    CONSTRAINT chk_processing_job_attempt_count
        CHECK (
            attempt_count >= 0
            AND max_attempts > 0
            AND attempt_count <= max_attempts
        ),

    CONSTRAINT chk_processing_job_target
        CHECK (
            (
                job_type IN (
                    'STT_TRANSCRIPTION',
                    'ANSWER_ANALYSIS'
                )
                AND answer_id IS NOT NULL
            )
            OR
            (
                job_type = 'FINAL_FEEDBACK_GENERATION'
                AND answer_id IS NULL
            )
        )
);

-- 답변 단위 작업은 같은 답변과 작업 유형의 중복 생성을 방지한다.
CREATE UNIQUE INDEX uk_processing_job_answer_type
    ON processing_job (answer_id, job_type)
    WHERE answer_id IS NOT NULL;

-- 세션 단위 작업은 같은 면접 세션과 작업 유형의 중복 생성을 방지한다.
CREATE UNIQUE INDEX uk_processing_job_session_type
    ON processing_job (interview_session_id, job_type)
    WHERE answer_id IS NULL;

-- 워커가 실행 가능한 작업을 상태와 다음 실행 시각 순서로 조회할 때 사용한다.
CREATE INDEX idx_processing_job_status_next_attempt_at
    ON processing_job (status, next_attempt_at);
