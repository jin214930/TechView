CREATE TABLE member
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email      VARCHAR(255)                            NOT NULL,
    password   VARCHAR(255)                            NOT NULL,
    nickname   VARCHAR(255)                            NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_member PRIMARY KEY (id),
    CONSTRAINT uk_member_email UNIQUE (email)
);

CREATE TABLE refresh_token
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    token      VARCHAR(255)                            NOT NULL,
    member_id  BIGINT                                  NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_refresh_token PRIMARY KEY (id),
    CONSTRAINT uk_refresh_token_token UNIQUE (token),
    CONSTRAINT fk_refresh_token_member
        FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE
);

-- PostgreSQL은 외래 키 컬럼의 인덱스를 자동 생성하지 않는다.
CREATE INDEX idx_refresh_token_member_id
    ON refresh_token (member_id);

-- 만료된 Refresh Token 정리 작업의 범위 조회를 지원한다.
CREATE INDEX idx_refresh_token_expires_at
    ON refresh_token (expires_at);
