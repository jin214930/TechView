DROP INDEX IF EXISTS idx_interview_session_member_started_at;

CREATE TABLE interview_daily_usage
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    member_id  BIGINT                                  NOT NULL,
    usage_date DATE                                    NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_interview_daily_usage PRIMARY KEY (id),
    CONSTRAINT uk_interview_daily_usage_member_date UNIQUE (member_id, usage_date),
    CONSTRAINT fk_interview_daily_usage_member
        FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE CASCADE
);
